class TestKupiec:
    INDEPENDENT = Sampling(horizon=5, step=5)

    def _flags(self, n: int, breaches: int) -> np.ndarray:
        flags = np.zeros(n, dtype=bool)
        flags[np.linspace(0, n - 1, breaches, dtype=int)] = True
        return flags

    def test_a_perfect_rate_scores_exactly_zero(self) -> None:
        result = kupiec(self._flags(1_000, 50), expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.statistic == pytest.approx(0.0, abs=1e-9)
        assert result.p_value == pytest.approx(1.0)

    def test_a_doubled_rate_matches_the_hand_computed_likelihood_ratio(self) -> None:
        """-2[900 ln.95 + 100 ln.05 - 900 ln.9 - 100 ln.1] = 41.3084."""
        result = kupiec(self._flags(1_000, 100), expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.statistic == pytest.approx(41.3084, abs=1e-3)
        assert result.p_value is not None and result.p_value < 1e-8

    def test_zero_breaches_is_scored_rather_than_crashing(self) -> None:
        """0 * log(0) is a defined term here, and a model that never breaches is wrong."""
        result = kupiec(np.zeros(100, dtype=bool), expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.statistic == pytest.approx(10.2587, abs=1e-3)
        assert result.detail["breaches"] == 0

    def test_zero_breaches_is_reported_from_the_exact_binomial(self) -> None:
        """The boundary. The chi-square approximation does not hold at x = 0.

        Kupiec's unrestricted maximum sits on the edge of the parameter space there, so
        its likelihood ratio is not chi-square on one degree of freedom. Concretely:
        0 breaches in 44 windows against a 5% quantile gives a chi-square p of 0.034,
        which reads as a rejection, and an exact p of 0.17, which does not.
        """
        result = kupiec(np.zeros(44, dtype=bool), expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.method == "exact_binomial"
        assert result.detail["chi2_p_value"] == pytest.approx(0.0336, abs=1e-3)
        assert result.p_value == pytest.approx(0.1721, abs=1e-3)
        # 0.95 ** 44, the one-sided reading the two-sided p-value is built from.
        assert result.detail["exact_lower_tail"] == pytest.approx(0.1047, abs=1e-3)
        assert result.detail["boundary_note"] is not None

    def test_all_breaches_is_also_a_boundary(self) -> None:
        result = kupiec(np.ones(30, dtype=bool), expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.method == "exact_binomial"

    def test_away_from_the_boundary_the_chi_square_is_used_and_the_two_agree(self) -> None:
        """Both are always computed, so the approximation can be checked where it holds."""
        result = kupiec(self._flags(580, 23), expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.method == "likelihood_ratio_chi2"
        assert result.p_value == pytest.approx(result.detail["chi2_p_value"], abs=1e-5)
        assert result.detail["exact_binomial_p_value"] == pytest.approx(
            result.detail["chi2_p_value"], abs=0.06
        )

    def test_the_joint_test_flags_a_boundary_component(self) -> None:
        """No exact analogue exists for the joint statistic, so it must not pretend."""
        flags = np.zeros(60, dtype=bool)
        flags[0] = True  # one breach, so independence is defined and the rate is not 0
        joint = conditional_coverage(flags, expected_rate=0.05, sampling=self.INDEPENDENT)

        assert joint.detail["boundary_note"] is None

        clean = conditional_coverage(
            np.zeros(60, dtype=bool), expected_rate=0.05, sampling=self.INDEPENDENT
        )
        assert clean.undefined_reason is not None

    def test_a_thin_sample_carries_a_power_note(self) -> None:
        result = kupiec(np.zeros(46, dtype=bool), expected_rate=0.01, sampling=self.INDEPENDENT)

        assert result.power_note is not None
        assert "absence of evidence" in result.power_note

    def test_a_thick_sample_carries_no_power_note(self) -> None:
        result = kupiec(self._flags(1_000, 50), expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.power_note is None


class TestChristoffersen:
    INDEPENDENT = Sampling(horizon=5, step=5)

    def test_clustered_breaches_are_caught(self) -> None:
        flags = np.zeros(200, dtype=bool)
        flags[:20] = True
        result = christoffersen_independence(flags, expected_rate=0.1, sampling=self.INDEPENDENT)

        assert result.p_value is not None and result.p_value < 0.01
        assert result.detail["breach_rate_after_breach"] > result.detail["breach_rate_after_calm"]

    def test_perfectly_alternating_breaches_are_also_caught(self) -> None:
        """Independence is two-sided: a breach that never repeats is not independent."""
        flags = np.arange(200) % 2 == 0
        result = christoffersen_independence(flags, expected_rate=0.5, sampling=self.INDEPENDENT)

        assert result.p_value is not None and result.p_value < 0.01

    def test_independent_breaches_are_not_flagged(self) -> None:
        flags = np.random.default_rng(23).random(2_000) < 0.05
        result = christoffersen_independence(flags, expected_rate=0.05, sampling=self.INDEPENDENT)

        assert result.p_value is not None and result.p_value > 0.05

    def test_no_breaches_leaves_the_test_undefined_rather_than_comfortable(self) -> None:
        """The failure this exists to prevent: p = 1.0 read as evidence of calibration."""
        result = christoffersen_independence(
            np.zeros(50, dtype=bool), expected_rate=0.01, sampling=self.INDEPENDENT
        )

        assert result.statistic is None
        assert result.p_value is None
        assert result.undefined_reason is not None
        assert "not identified" in result.undefined_reason

    def test_conditional_coverage_is_undefined_when_a_component_is(self) -> None:
        result = conditional_coverage(
            np.zeros(50, dtype=bool), expected_rate=0.01, sampling=self.INDEPENDENT
        )

        assert result.statistic is None
        assert result.undefined_reason is not None

    def test_conditional_coverage_sums_its_components(self) -> None:
        flags = np.random.default_rng(31).random(500) < 0.08
        rate = kupiec(flags, expected_rate=0.05, sampling=self.INDEPENDENT)
        independence = christoffersen_independence(
            flags, expected_rate=0.05, sampling=self.INDEPENDENT
        )
        joint = conditional_coverage(flags, expected_rate=0.05, sampling=self.INDEPENDENT)

        assert rate.statistic is not None and independence.statistic is not None
        assert joint.statistic == pytest.approx(rate.statistic + independence.statistic)


class TestReliability:
    def test_a_constant_climatological_forecast_is_reliable_and_useless(self) -> None:
        """Reliability zero, resolution zero. Only the pair distinguishes it from skill."""
        outcomes = np.array([1.0, 0.0] * 100)
        curve = reliability_curve(np.full(200, 0.5), outcomes)

        assert curve.brier == pytest.approx(0.25)
        assert curve.reliability == pytest.approx(0.0, abs=1e-12)
        assert curve.resolution == pytest.approx(0.0, abs=1e-12)
        assert curve.uncertainty == pytest.approx(0.25)

    def test_the_decomposition_reconstructs_the_score_when_bins_are_pure(self) -> None:
        probabilities = np.repeat([0.05, 0.45, 0.95], 200)
        rng = np.random.default_rng(41)
        outcomes = (rng.random(600) < probabilities).astype(float)
        curve = reliability_curve(probabilities, outcomes)

        assert curve.binning_error == pytest.approx(0.0, abs=1e-12)

    def test_an_overconfident_forecast_has_a_large_reliability_term(self) -> None:
        """Says 90%, happens half the time: the calibration term is (0.9-0.5)^2."""
        outcomes = np.array([1.0, 0.0] * 100)
        curve = reliability_curve(np.full(200, 0.9), outcomes)

        assert curve.reliability == pytest.approx(0.16)

    def test_brier_rejects_a_probability_outside_the_unit_interval(self) -> None:
        with pytest.raises(ValueError, match=r"\[0, 1\]"):
            brier_score(np.array([1.4]), np.array([1.0]))

    def test_empty_bins_are_kept(self) -> None:
        """``min_positives=0`` because this is the axis rule, not the withholding rule."""
        curve = reliability_curve(np.full(10, 0.05), np.zeros(10), min_positives=0)
        empty = [b for b in curve.bins if b.count == 0]

        assert len(empty) == 9
        assert all(b.observed_rate is None for b in empty)


class TestARareEventGetsAScoreButNotADiagram:
    """The pre-registered rule, written before the hurdle event existed.

    Fifteen positives in 580 windows cannot support a ten-bin diagram. The score, the
    base rate and the count survive at any sample size and are what the reader gets.
    """

    def _rare(self, positives: int, n: int = 580) -> tuple[np.ndarray, np.ndarray]:
        outcomes = np.zeros(n)
        outcomes[:positives] = 1.0
        rng = np.random.default_rng(3)
        return np.clip(rng.normal(positives / n, 0.01, n), 0.0, 1.0), outcomes

    def test_below_the_threshold_the_curve_is_withheld(self) -> None:
        curve = reliability_curve(*self._rare(positives=8))

        assert curve.withheld
        assert curve.bins == ()
        assert "too few to draw" in (curve.withheld_reason or "")

    def test_the_score_and_the_count_survive_the_withholding(self) -> None:
        curve = reliability_curve(*self._rare(positives=8))

        assert curve.positives == 8
        assert curve.base_rate == pytest.approx(8 / 580)
        assert curve.brier > 0.0
        assert curve.describe()["positive_events"] == 8

    def test_the_mean_forecast_survives_the_withholding_too(self) -> None:
        """A scalar is not a diagram, and withholding it with one was a reporting bug.

        `mean_forecast` against `base_rate` is the model's bias on this event, and it
        is the number that says whether a modelled tail is the right shape rather than
        merely non-Gaussian. The argument for withholding a ten-bin curve at eight
        positives — each bin resting on one or two events — says nothing about a single
        mean taken over all 580 forecasts. A rare event is where that comparison
        matters most, so withholding it there was exactly backwards.
        """
        probabilities, outcomes = self._rare(positives=8)
        curve = reliability_curve(probabilities, outcomes)

        assert curve.withheld
        assert curve.bins == ()
        assert curve.mean_forecast == pytest.approx(float(np.mean(probabilities)))
        assert curve.describe()["mean_forecast"] == pytest.approx(
            round(float(np.mean(probabilities)), 4)
        )

    def test_the_mean_forecast_is_taken_over_every_forecast_not_the_drawn_bins(
        self,
    ) -> None:
        """Averaging the bin means would weight a bin holding one forecast equally
        with a bin holding five hundred, and would be undefined when none are drawn."""
        probabilities, outcomes = self._rare(positives=40)
        curve = reliability_curve(probabilities, outcomes)

        assert not curve.withheld
        assert curve.mean_forecast == pytest.approx(float(np.mean(probabilities)))
        assert curve.describe()["forecast_bias"] == pytest.approx(
            round(curve.mean_forecast - curve.base_rate, 4)
        )

    def test_at_the_threshold_the_curve_is_drawn(self) -> None:
        curve = reliability_curve(*self._rare(positives=MIN_POSITIVE_EVENTS))

        assert not curve.withheld
        assert curve.bins

    def test_the_threshold_is_the_one_the_coverage_tests_already_use(self) -> None:
        """Taken from the neighbouring test rather than tuned to this event."""
        assert float(MIN_POSITIVE_EVENTS) == MIN_EXPECTED_BREACHES

    def test_a_low_brier_on_a_rare_event_is_not_a_better_forecast(self) -> None:
        """Why the count is published beside the score: these are not comparable."""
        rare = reliability_curve(*self._rare(positives=15))
        coin = reliability_curve(np.full(580, 0.5), np.array([1.0, 0.0] * 290))

        assert rare.brier < coin.brier
        assert rare.uncertainty < coin.uncertainty
        # Against its own uncertainty term the rare event has learned nothing either.
        assert rare.resolution == pytest.approx(0.0, abs=1e-3)


class TestTheHurdleEvent:
    """The one event friction defines, graded by the machinery that already existed."""

    ENSEMBLE = None

    def _ensemble(self, terminals: np.ndarray) -> object:
        from aurex.dist.paths import PathEnsemble

        return PathEnsemble(prices=terminals.reshape(-1, 1), anchor=100.0, diagnostics={})

    def test_it_is_a_binary_event_like_any_other(self) -> None:
        """The design bet: friction changes the level, not the kind of question."""
        from aurex.score.events import BinaryEvent

        assert isinstance(ClearsHurdle(multiple=1.0937), BinaryEvent)

    def test_the_probability_is_the_share_of_paths_clearing_the_hurdle(self) -> None:
        # Deliberately off the boundary: anchor * multiple is a float product, so a
        # terminal sitting exactly on the level is decided by rounding rather than by
        # anything meaningful. Real ensembles land there with probability zero.
        ensemble = self._ensemble(np.array([100.0, 105.0, 111.0, 115.0]))

        assert ClearsHurdle(multiple=1.10).probability(ensemble) == pytest.approx(0.5)

    def test_it_is_resolved_at_the_horizon_not_on_the_way(self) -> None:
        """A round trip is closed at the end; a path that touched and fell back did not
        clear it for the holder this event grades."""
        event = ClearsHurdle(multiple=1.05)
        touched_and_fell_back = RealisedPath(np.array([100.0, 108.0, 101.0]))

        assert event.monitoring == "terminal"
