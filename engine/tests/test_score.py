class TestCrps:
    def test_a_single_path_scores_as_absolute_error(self) -> None:
        """One path is a point forecast, and CRPS must collapse to |x - y|."""
        assert crps(np.array([104.0]), 100.0) == pytest.approx(4.0)

    def test_matches_the_analytic_gaussian_value(self) -> None:
        """CRPS(N(0,1), 0) = 2*phi(0) - 1/sqrt(pi), which pins the estimator exactly."""
        sample = stats.norm.rvs(size=200_000, random_state=np.random.default_rng(3))
        expected = 2.0 * stats.norm.pdf(0.0) - 1.0 / math.sqrt(math.pi)

        assert crps(sample, 0.0) == pytest.approx(expected, abs=0.004)

    def test_the_naive_estimator_penalises_a_small_ensemble(self) -> None:
        """The naive form subtracts too little spread, so it scores worse by ~1/M.

        Which is the incentive the fair estimator removes: under the naive score a
        model wins a benchmark by simulating more paths. The gap must also shrink as
        the ensemble grows, or the correction is not the one being described.
        """
        rng = np.random.default_rng(5)
        small = rng.normal(size=100)
        large = rng.normal(size=10_000)

        assert crps(small, 0.3, fair=False) > crps(small, 0.3, fair=True)
        small_gap = crps(small, 0.3, fair=False) - crps(small, 0.3, fair=True)
        large_gap = crps(large, 0.3, fair=False) - crps(large, 0.3, fair=True)

        assert large_gap < small_gap / 50.0

    def test_a_tighter_correct_forecast_scores_better(self) -> None:
        rng = np.random.default_rng(9)
        tight = rng.normal(scale=1.0, size=20_000)
        loose = rng.normal(scale=4.0, size=20_000)

        assert crps(tight, 0.0) < crps(loose, 0.0)

    def test_skill_against_an_identical_score_is_exactly_zero(self) -> None:
        assert crps_skill(2.5, 2.5) == 0.0

    def test_skill_against_a_zero_baseline_is_refused(self) -> None:
        with pytest.raises(ValueError, match="must be positive"):
            crps_skill(1.0, 0.0)


class TestPit:
    """The randomisation is the point; these tests are what it buys."""

    def _values(self, *, ensemble_size: int, observation_scale: float, trials: int) -> np.ndarray:
        rng = np.random.default_rng(17)
        return np.array(
            [
                pit_value(
                    rng.normal(size=ensemble_size),
                    float(rng.normal() * observation_scale),
                    rng=rng,
                )
                for _ in range(trials)
            ]
        )

    def test_a_correct_forecast_gives_uniform_pit_even_for_a_small_ensemble(self) -> None:
        """Fifty paths. The unrandomised PIT would pile mass on the endpoints here."""
        values = self._values(ensemble_size=50, observation_scale=1.0, trials=3_000)
        result = uniformity(values, sampling=Sampling(horizon=1, step=1))

        assert result.p_value > 0.05

    def test_an_overconfident_forecast_is_caught(self) -> None:
        """Observations twice as dispersed as the ensemble: PIT piles at both ends."""
        values = self._values(ensemble_size=200, observation_scale=2.0, trials=3_000)
        result = uniformity(values, sampling=Sampling(horizon=1, step=1))

        assert result.p_value < 1e-6

    def test_pit_stays_inside_the_unit_interval(self) -> None:
        rng = np.random.default_rng(2)
        sample = rng.normal(size=20)

        assert 0.0 < pit_value(sample, 1e9, rng=rng) < 1.0
        assert 0.0 < pit_value(sample, -1e9, rng=rng) < 1.0

    def test_an_empty_ensemble_has_no_pit(self) -> None:
        with pytest.raises(ValueError, match="empty ensemble"):
            pit_value(np.array([]), 1.0, rng=np.random.default_rng(0))


class TestChiSquareComplementsKs:
    """Why both are published: they fail on different shapes."""

    INDEPENDENT = Sampling(horizon=1, step=1)

    def _bin_counts(self, counts: list[int]) -> np.ndarray:
        """Exactly these per-bin counts, spread evenly inside each bin.

        Constructed rather than sampled: the point is a property of the two statistics,
        and sampling noise would only make the comparison flakier without making it
        more real.
        """
        values: list[float] = []
        for index, count in enumerate(counts):
            values.extend((index + (np.arange(count) + 0.5) / count) / len(counts))
        return np.array(sorted(values))

    def test_chi_square_sees_mass_in_one_bin_that_ks_is_weak_against(self) -> None:
        """A displaced bin barely moves the CDF, and the CDF is all KS looks at.

        1,500 observations with 45 moved from the ninth bin into the tenth. The largest
        cumulative deviation is 3%, which KS cannot separate from noise; the two bin
        counts are 30% off their expectation, which chi-square sees immediately. This
        is exactly the shape the gold PIT histograms show, which is why both tests are
        published rather than only the conventional one.
        """
        counts = [150] * 10
        counts[7] -= 45
        counts[8] += 45
        values = self._bin_counts(counts)

        ks = uniformity(values, sampling=self.INDEPENDENT)
        chi = chi_square_uniformity(values, sampling=self.INDEPENDENT)

        assert ks.p_value > 0.10, "KS was expected to miss this"
        assert chi.p_value < 0.01, "chi-square was expected to catch it"

    def test_both_pass_on_a_genuinely_uniform_sample(self) -> None:
        values = np.random.default_rng(5).random(2_000)

        assert uniformity(values, sampling=self.INDEPENDENT).p_value > 0.05
        assert chi_square_uniformity(values, sampling=self.INDEPENDENT).p_value > 0.05

    def test_a_thin_sample_is_flagged_as_an_unreliable_approximation(self) -> None:
        result = chi_square_uniformity(
            np.random.default_rng(3).random(44), sampling=self.INDEPENDENT, bins=10
        )

        assert result.expected_per_bin == pytest.approx(4.4)
        assert result.underpowered
        assert result.describe()["validity_note"] is not None

    def test_it_refuses_overlapping_windows_like_every_other_p_value(self) -> None:
        with pytest.raises(OverlappingWindowsError):
            chi_square_uniformity(np.linspace(0.0, 1.0, 100), sampling=Sampling(horizon=21, step=5))

    def test_degrees_of_freedom_are_one_less_than_the_bins(self) -> None:
        result = chi_square_uniformity(
            np.random.default_rng(1).random(500), sampling=self.INDEPENDENT, bins=8
        )

        assert result.degrees_of_freedom == 7


