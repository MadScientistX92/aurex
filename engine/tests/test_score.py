"""§3a's scoring tests.

Three layers, because they fail differently:

* **Closed forms.** CRPS against the analytic Gaussian value, Kupiec against a
  likelihood ratio computed by hand. If these drift, a metric is wrong and every
  number built on it is wrong with it.
* **Boundaries.** The overlap guard, the missing-baseline argument, the shape of
  :class:`RealisedPath`. These are the invariants that would otherwise be a docstring,
  and each is tested by building the thing that should be rejected.
* **The harness end to end.** No lookahead, a driftless null, and — on a series
  generated by a process with real volatility clustering — a positive CRPS skill.
  That last one is not a view about markets: it is the mechanical claim that a
  correctly specified conditional model beats an unconditional one on data that
  actually conditions.
"""

