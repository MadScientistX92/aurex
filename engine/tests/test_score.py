def price_series(
    *, periods: int = 1_600, seed: int = 11, start: str = "2016-01-01", **kwargs: float
) -> pd.Series:
    """A price path from a known GJR process, so calibration has a right answer."""
    frame = simulate_gjr_path(periods=periods, seed=seed, start=start, **kwargs)
    values = 100.0 * np.exp(np.cumsum(frame["returns"].to_numpy()))
    return pd.Series(values, index=frame.index, name="price")


